#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""qa-agent 执行脚本：把"测一下 / 验收一下 / 看看有没有问题"落成可执行、可打勾的用例与缺陷口径。

不做"我帮你想想可能的问题"（那是闲聊），做的是三件能让评审当场卡住的事：
① 模糊验收词换成可测指标——"流畅""稳定""好用"在验收会上无法判定，必须换数字；
② 用例按等价类/边界/异常路径三张表铺开，避免只测"正常走一遍"；
③ 缺陷分级给出**判定门槛**，避免"这是阻塞还是严重"每次都吵。

一条硬规矩：没有复现步骤的缺陷不叫缺陷，叫抱怨。所以每条用例都要求写清前置条件与预期。
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
import _common as C  # noqa: E402
import _topic_guard as TG  # noqa: E402

# 模糊词 → 可测指标。这是本脚本最有用的部分：验收会上的争论八成来自这类词。
VAGUE_TO_METRIC = {
    "流畅": ("帧率与掉帧", "目标机型 P1 帧率 ≥ 55、掉帧率 < 1%、单次卡顿 > 100ms 的次数为 0"),
    "稳定": ("崩溃与错误率", "崩溃率 < 0.1%/会话、无数据丢失级错误、连续 8 小时不重启不劣化"),
    "快速": ("时延分位", "P95 < 300ms、P99 < 800ms；首屏在 4G 下 < 1.5s"),
    "快": ("时延分位", "P95 < 300ms；冷启动 < 2s（同一台测试机同一版本）"),
    "好看": ("视觉走查", "按设计稿逐项走查：间距/字号/色值/图标对齐，偏差项为 0"),
    "好用": ("任务成功率", "首次使用者完成核心任务的成功率 ≥ 80%，平均步数 ≤ 5"),
    "兼容": ("机型覆盖", "覆盖 Top 20 机型 + 最低配置机；每机型跑通核心路径"),
    "安全": ("越权用例", "越权/注入/重放三类用例全部拒绝，且拒绝有审计记录"),
    "智能": ("准确率", "给定标注集的准确率与拒答率，二者必须同时报告（只报准确率＝刷分）"),
    "性能": ("吞吐与资源", "给定并发下的 QPS 与内存峰值；单请求内存增量可核算"),
    "差不多": ("容差", "明确写清允许偏差（如 ±5%），否则无法判定通过"),
    "尽量": ("硬门槛", "把「尽量」换成必须满足的门槛，否则等于没要求"),
}

# 用例三张表：只测正常路径是最常见的漏测来源。
CASE_TABLES = [
    ("等价类", [
        ("有效等价类", "合法输入各取一个代表值即可，不必穷举"),
        ("无效等价类", "非法输入必须逐个验证并给出明确报错，不能静默失败"),
    ]),
    ("边界值", [
        ("下边界", "0 / 1 / 空字符串 / 空列表"),
        ("上边界", "最大值、最大长度、刚好超一位"),
        ("越界", "负数、超长、超深嵌套、超大文件"),
        ("特殊值", "空白、全角、emoji、换行、零宽字符"),
    ]),
    ("异常路径", [
        ("网络", "断网、弱网、请求超时、响应乱序"),
        ("并发", "重复提交、并发写同一资源、任务中途取消"),
        ("权限", "未登录、无权限、权限中途被收回"),
        ("外部依赖", "下游 5xx、下游变慢、第三方返回格式变了"),
        ("中途退出", "提交中断、刷新页面、进程被杀后的状态是否可恢复"),
    ]),
]

# 缺陷分级：给判定门槛，不给形容词。
DEFECT_LEVELS = [
    ("阻塞", "主流程走不通 / 数据丢失或错乱 / 崩溃且可稳定复现 → 必须当版修复，不得延期"),
    ("严重", "核心功能结果错误但可绕过；或仅特定条件下触发 → 当版修复，若有可行绕行可评估延期"),
    ("一般", "非核心功能错误、文案错误、异常提示缺失 → 排入下个迭代"),
    ("轻微", "视觉偏差、体验瑕疵，不影响任务完成 → 随版本顺手修"),
]

# 回归裁剪：改动点决定必测项，不做全量也不裸奔。
#
# 每条规则自带**触发词**。第一版把「接口/数据/权限/并发/计费」无条件并进判据，
# 等于条件恒真 —— 不管目标说什么，五条回归都会全量输出，"裁剪"就此变成"堆清单"。
# 判据必须由目标内容决定，否则它不是判据，只是排版。
REGRESSION_RULES = [
    ("改了数据模型", ("数据模型", "表结构", "字段", "迁移", "schema", "数据库", "存储"),
     "必测：读写迁移、旧数据兼容、回滚路径"),
    ("改了接口契约", ("接口", "api", "契约", "字段返回", "协议", "响应格式"),
     "必测：调用方全量回归、错误码变化、字段可空性"),
    ("改了权限逻辑", ("权限", "鉴权", "登录", "越权", "角色", "token", "rbac"),
     "必测：越权用例、匿名访问、权限变更后的会话失效"),
    ("改了并发/异步", ("并发", "异步", "队列", "重试", "线程", "任务", "流式", "sse"),
     "必测：重复提交、超时重试、任务取消、乱序响应"),
    ("改了计费/额度", ("计费", "额度", "预算", "扣费", "配额", "账单", "对账"),
     "必测：边界额度、并发扣减、退款或补回、对账一致性"),
    ("纯文案/样式", ("文案", "样式", "颜色", "字号", "提示语", "措辞"),
     "必测：目标页面走查 + 关键流程冒烟，不必全量回归"),
]

def work():
    g = C.goal()
    kw = C.keywords(g, 8)
    # 主题走守卫：实测 `_common.topic` 会切出「批接口改」这种单字动词开头的碎片。
    topic = TG.pick(g, kw, "未命名待测对象", domain="qa")

    # 模糊词识别：命中的词换成可测指标，这是本脚本的第一优先输出。
    metrics = []
    for w, (name, spec) in VAGUE_TO_METRIC.items():
        if w in g and name not in [m["metric"] for m in metrics]:
            metrics.append({"vague_word": w, "metric": name, "accept_when": spec})

    # 改动类型 → 回归范围：只展开目标里真的提到的那几类，避免堆无关清单。
    low = g.lower()
    regression = [
        {"changed": name, "must_test": must}
        for name, triggers, must in REGRESSION_RULES
        if any(tr in low for tr in triggers)
    ]

    tasks = [s.strip() for s in C.split_sentences(g, by_comma=True) if len(s.strip()) >= 2][:10]

    # 识别不到改动点时**不能**在 regression_scope 里放一条「未识别改动点」占位：
    # 那个字段的语义是"已识别的结论"，占位符会让下游把"没答案"当成答案渲染出来。
    # 实测证据：把一句纯市场目标喂进来，regression_scope 仍吐出一条占位，
    # 门禁 21 的「跨域隔离」当场红（2026-11-14）。提示改挂到待办里——它是要你补的信息，
    # 不是一个结论，语义这才对得上。
    if not regression:
        tasks = tasks[:9] + ["先说明改了什么（数据 / 接口 / 权限 / 并发 / 计费），否则回归范围无从裁剪"]

    case_count = sum(len(items) for _, items in CASE_TABLES)

    payload = {
        "ok": True,
        "topic": topic,
        "keywords": kw,
        "metrics_from_vague": metrics,
        "case_tables": [
            {"table": name, "items": [{"kind": k, "note": n} for k, n in items]}
            for name, items in CASE_TABLES
        ],
        "defect_levels": [{"level": l, "gate": d} for l, d in DEFECT_LEVELS],
        "regression_scope": regression,
        "open_subtasks": [{"no": i, "task": t,
                           "need": "定稿：前置条件 + 操作步骤 + 预期结果 + 判定门槛"}
                          for i, t in enumerate(tasks, 1)],
        "rule": "没有复现步骤（前置条件 / 操作 / 预期）的不是缺陷；没有数字的验收标准不算通过条件",
    }
    summary = (
        f"《{topic}》测试口径：模糊验收词转指标 {len(metrics)} 条、"
        f"用例表 {len(CASE_TABLES)} 张共 {case_count} 类、缺陷 {len(DEFECT_LEVELS)} 级带门槛、"
        f"回归范围 {len(regression)} 条、待补用例 {len(tasks)} 项。"
    )
    return summary, payload


if __name__ == "__main__":
    C.main(work)
