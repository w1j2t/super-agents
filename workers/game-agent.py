#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""game-agent 执行脚本：把"做个玩法 / 改个数值"的目标，落成可评审的设计检查表。

不做美术与剧情创作（那需要模型），做的是策划案评审时**最容易被跳过、又最贵**的
三件事：核心循环有没有闭环、数值轴会不会通胀、失败模式有没有预案。
每条都带"怎么判断它坏了"的判定信号——没有判定信号的检查项等于一句正确的废话。
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
import _common as C  # noqa: E402

# 品类 → (品类名, 该品类最典型的那个坑)
GENRES = {
    "修仙": ("修仙 / 成长向 RPG", "境界墙：突破材料只在前一张图掉，玩家会卡住而不是变强"),
    "rpg": ("RPG", "支线奖励与主线进度脱钩，玩家跳过支线后主线数值对不上"),
    "肉鸽": ("Roguelike / 肉鸽", "单局构筑强度方差过大，一半局在开局就注定失败"),
    "roguelike": ("Roguelike / 肉鸽", "单局构筑强度方差过大，一半局在开局就注定失败"),
    "模拟": ("模拟经营", "产能指数增长而需求线性增长，中期后无事可做"),
    "经营": ("模拟经营", "产能指数增长而需求线性增长，中期后无事可做"),
    "塔防": ("塔防", "后期波次靠血量硬堆，解法收敛成唯一最优解"),
    "开放世界": ("开放世界", "地图密度不足，跑图时间挤占了玩法时间"),
    "回合制": ("回合制战斗", "速度线决定一切，慢速角色在最优解里没有位置"),
    "动作": ("动作 / 战斗", "无敌帧与硬直参数不匹配，手感只能靠玩家自己适应"),
    "moba": ("MOBA", "英雄强度靠数值补丁平衡，机制差异被抹平"),
    "卡牌": ("卡牌 / 构筑", "稀有度直接等于强度，构筑深度被卡池深度替代"),
    "技能树": ("成长向 RPG", "技能树深度靠数值堆而非机制组合，中期退化成一条最优路线"),
    "战斗": ("动作 / 战斗", "无敌帧与硬直参数不匹配，手感只能靠玩家自己适应"),
    "关卡": ("关卡驱动型", "关卡难度靠怪量硬堆，失败原因无法归因到玩家操作"),
}

# 主题兜底：`_common.topic` 对「设计…」「改造…」这类开头不在 _LEAD_VERBS 的句子，
# 会退化成句中最早露出的实词锚点，实测得到「设计」这种动词当主题。这里只在本文件
# 兜底，不去动公共分词（那层有自己的门禁 16，改它的风险远大于收益）。
TOPIC_NOISE = {"设计", "做个", "玩法", "系统", "方案", "优化", "调整"}

# 核心循环三段：缺任何一段，玩法都会在 2 小时内被看穿。
CORE_LOOP = [
    ("行动", "玩家每次循环做的**同一个**主动作是什么？（砍怪 / 建造 / 抽卡 / 交易）"),
    ("反馈", "这个动作在多长时间内给出可见回报？超过 10 秒无反馈，循环会失去黏性"),
    ("成长", "回报如何转化为下次循环的**能力提升**？只给货币不给能力＝空转"),
]

# 数值轴：每项都写清"正常区间"与"坏掉的信号"。
BALANCE_AXES = [
    ("成长曲线", "前期近似线性、中期加速、后期收敛",
     "全程指数：30 小时后伤害数字失去直觉，玩家改用攻略而不是判断"),
    ("资源产出 vs 消耗", "产出必须被消耗端吃掉（修理/合成/门票/税）",
     "产出无出口：仓库爆满，货币贬值，商店定价形同虚设"),
    ("战力差", "越级收益应随风险同步上升，且存在软上限",
     "越级零风险：所有人只刷越级点，正常地图变成摆设"),
    ("时间成本", "单次循环时长 × 循环次数 ≈ 目标留存节点",
     "单次过长：一次失败就流失；单次过短：操作疲劳先于成就感到来"),
    ("概率与保底", "公示概率必须与实现一致，保底次数要可核算",
     "保底与公示不符：这是合规问题，不只是体验问题"),
]

FAILURE_MODES = [
    ("循环无反馈", "做了动作但界面/数值没有变化，玩家无法确认自己有效"),
    ("正反馈失控", "强者愈强且没有制衡，中期就失去张力"),
    ("数值通胀", "后期数值膨胀到失去直觉，决策退化为看数字大小"),
    ("无意义选择", "两个选项数学等价，选择只是延迟点击"),
    ("单点依赖", "只有一个玩法有产出，其余系统都是装饰"),
    ("缺乏失败成本", "失败不付出任何代价，紧张感归零"),
]


def work():
    g = C.goal()
    low = g.lower()
    kw = C.keywords(g, 8)
    topic = C.topic(g)
    if not topic or len(topic) < 3 or topic in TOPIC_NOISE:
        topic = kw[0] if kw else "未命名玩法"

    hit = []
    for k, (name, pit) in GENRES.items():
        if k in low and name not in [h[0] for h in hit]:
            hit.append((name, pit))
    if not hit:
        hit = [("未识别（需先确认品类：RPG / 肉鸽 / 模拟经营 / 动作 …）",
                "品类不明时数值无从校准——先定品类，再谈平衡")]

    # 目标里用逗号/顿号列出的子系统，逐条转成"待定稿子任务"，避免漏项。
    tasks = [s.strip() for s in C.split_sentences(g, by_comma=True) if len(s.strip()) >= 2][:8]

    payload = {
        "ok": True,
        "topic": topic,
        "keywords": kw,
        "genre": [{"name": n, "typical_pitfall": p} for n, p in hit],
        "core_loop": [
            {"stage": s, "must_answer": q} for s, q in CORE_LOOP
        ],
        "balance_axes": [
            {"axis": a, "healthy": h, "broken_signal": b} for a, h, b in BALANCE_AXES
        ],
        "failure_modes": [{"mode": m, "how_to_spot": h} for m, h in FAILURE_MODES],
        "open_subtasks": [{"no": i, "task": t, "need": "定稿：目标值 + 判定门槛 + 验收方式"}
                          for i, t in enumerate(tasks, 1)],
        "rule": "数值改动必须给出「改前—改后—预期影响」三列，只写「调低一点」不算方案",
    }
    summary = (
        f"《{topic}》识别为 {hit[0][0]}；核心循环 {len(CORE_LOOP)} 段待回答、"
        f"数值轴 {len(BALANCE_AXES)} 项已附失效信号、失败模式 {len(FAILURE_MODES)} 条、"
        f"子任务 {len(payload['open_subtasks'])} 条待定稿。"
    )
    return summary, payload


if __name__ == "__main__":
    C.main(work)
